function dayIndexFromYMD(year: number, month: number, day: number): number {
  const daysSinceEpoch = Math.floor(Date.UTC(year, month, day) / 86_400_000);
  return ((daysSinceEpoch % VERSES_OF_THE_DAY.length) + VERSES_OF_THE_DAY.length) % VERSES_OF_THE_DAY.length;
}

export function getVerseOfTheDayUTC(now: Date = new Date()): DailyVerse {
  const idx = dayIndexFromYMD(
    now.getUTCFullYear(),
    now.getUTCMonth(),
    now.getUTCDate()
  );
  return VERSES_OF_THE_DAY[idx];
}

export function getVerseOfTheDayLocal(now: Date = new Date()): DailyVerse {
  const idx = dayIndexFromYMD(
    now.getFullYear(),
    now.getMonth(),
    now.getDate()
  );
  return VERSES_OF_THE_DAY[idx];
}
